    [InlineData("Mortal.Kombat.II.2026.German.5.1.AC3.MD.1080p.DCPRip.x264-LiNEUP", "HDTV-1080p")]
    public void Parses_owner_folder_names(string name, string expected)
    {
        var result = QualityParser.ParseQuality(name);

        Assert.Equal(expected, result.Quality.Name);
        Assert.Equal(1, result.Revision.Version);
        Assert.False(result.Revision.IsRepack);
    }

    [Fact]
    public void Proper_raises_version()
    {
        var result = QualityParser.ParseQuality("Show.S01E05.PROPER.1080p.WEB.h264-GRP");

        Assert.Equal(Quality.WebDl1080p, result.Quality);
        Assert.Equal(2, result.Revision.Version);
        Assert.False(result.Revision.IsRepack);
    }

    [Fact]
    public void Repack_raises_version_and_sets_repack()
    {
        var result = QualityParser.ParseQuality("Show.S01E05.REPACK.720p.HDTV.x264-GRP");

        Assert.Equal(Quality.Hdtv720p, result.Quality);
        Assert.Equal(2, result.Revision.Version);
        Assert.True(result.Revision.IsRepack);
    }

